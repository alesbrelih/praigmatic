// mustGetEnv retrieves an env var or fatals if unset/empty.
// Use for required configuration — fail fast at startup, not at runtime.
func mustGetEnv(key string) string {
	val := os.Getenv(key)
	if val == "" {
		log.Fatalf("required environment variable %s is not set", key)
	}
	return val
}

// mustConnectDB opens a database connection or fatals on failure.
func mustConnectDB(dbURL string) *sql.DB {
	db, err := sql.Open("postgres", dbURL)
	if err != nil {
		log.Fatalf("failed to open database: %v", err)
	}
	if err := db.Ping(); err != nil {
		log.Fatalf("failed to connect to database: %v", err)
	}
	return db
}

// Repository defines the interface for the data access layer.
// Mocks are generated by mockery v3 via .mockery.yaml config.
type Repository interface {
	Get(ctx context.Context, id string) (*Item, error)
	Create(ctx context.Context, item *Item) error
	Update(ctx context.Context, item *Item) error
	WithTx(tx *sql.Tx) Repository
}

// Item represents a domain entity
type Item struct {
	ID   string
	Name string
}

// Service represents the business logic layer
type Service struct {
	db   *sql.DB
	repo Repository
}

// NewService creates a new service.
// All deps are provided by main — no nil checks needed.
func NewService(db *sql.DB, repo Repository) *Service {
	return &Service{db: db, repo: repo}
}

